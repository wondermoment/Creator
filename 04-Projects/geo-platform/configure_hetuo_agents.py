def run():
 with s.db() as c:
  pid=c.execute('SELECT id FROM projects WHERE name=?',('和拓实业',)).fetchone()[0]
  for aid,(name,personality,work) in JOBS.items():
   md=f'# {name}\n\n开场白：我是{name}，先核对和拓项目中的资料与进度，再把需求落到可验收的产物。\n\n## 企业边界\n仅服务和拓实业（上海）有限公司 / 和拓化学 HEROTO，官网 www.heroto.com.cn，项目 {pid}。\n\n## 性格\n{personality}\n\n## 职责与验收\n{work}\n\n## 共同方法与限制\n{METHOD}\n'
   old=next((x for x in s.items(c,pid,'soul') if x['agent_id']==aid),None)
   if old and old['markdown']==md:continue
   if old:s.put(c,pid,'soul_history',old)
   s.put(c,pid,'soul',{'agent_id':aid,'markdown':md,'version':old['version']+1 if old else 2},old['id'] if old else None)
   folder=s.DB_PATH.parent/'agents'/pid/aid;folder.mkdir(parents=True,exist_ok=True);(folder/'soul.md').write_text(md,encoding='utf-8')
  for base,(name,task) in SKILLS.items():
   prompt=task+'\n\n'+METHOD
   old=next((x for x in s.items(c,pid,'skill') if x['base_id']==base),None)
   if old and old['prompt']==prompt:continue
   s.put(c,pid,'skill',{'base_id':base,'name':name,'prompt':prompt,'version':old['version']+1 if old else 1,'base_version':1},old['id'] if old else None)
  print(s.dump({'project_id':pid,'souls':len(JOBS),'skills':len(SKILLS)}))

if __name__=='__main__':run()
